'use strict';
// Generate endpoint-based wires from the current IOC geometry.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {buildModel,root}=require('./harness.cjs');
const model=buildModel(),name=path.basename(__dirname);
const window={addEventListener(){},AliceOledDevice:require(path.join(root,'oled-device.js')),AliceSpiDisplayDevice:require(path.join(root,'spi-display-device.js')),AlicePeripheralCatalog:require(path.join(root,'peripheral-catalog.js')),AlicePeripheralDevices:require(path.join(root,'peripheral-devices.js'))};
const context=vm.createContext({window,document:{readyState:'loading',addEventListener(){},body:null},Blob,console,queueMicrotask,setTimeout,clearTimeout,CustomEvent:function(t,o){this.type=t;this.detail=o&&o.detail;}});
vm.runInContext(fs.readFileSync(path.join(root,'schematic.js'),'utf8').replace('var publicApi = {','var publicApi = { definitionsForTest: function(){return componentDefinitions;},'),context);
const api=window.AliceSchematic;api.applyProjectModel(model);const defs=api.definitionsForTest();
const components=[],wires=[];
function add(id,type,x,y,value,extra={}){components.push({id,type,ref:id.toUpperCase(),x,y,value,rotation:0,autoGenerated:false,...extra});}
add('mcu','mcu',360,200,'STM32F103C8T6');add('power','vcc',400,65,'+3V3');add('ground','ground',400,540,'0V');
function p(id,pin){const c=components.find(c=>c.id===id),pinDef=defs[c.type].pins.find(p=>p.name===pin);if(!pinDef)throw Error(id+':'+pin);return{x:c.x+pinDef.x,y:c.y+pinDef.y};}
function wire(a,ap,b,bp){const start=p(a,ap),end=p(b,bp);wires.push({id:'w'+(wires.length+1),from:{componentId:a,pin:ap},to:{componentId:b,pin:bp},signal:ap,route:[start,{x:end.x,y:start.y},end],autoGenerated:false});}
wire('power','VCC','mcu','VDD');wire('mcu','VSS','ground','GND');
if(name.includes('UART')){
 add('r-led','resistor',660,300,'330 Ohm');add('led','led',810,300,'COMMAND',{ledColor:'green'});
 wire('mcu','PB12','r-led','1');wire('r-led','2','led','A');wire('led','K','ground','GND');
}else if(name.includes('I2C')){
 add('oled','oled',730,230,'SSD1306 0x3C',{oledAddress:60});add('r-scl','resistor',620,100,'4.7 kOhm');add('r-sda','resistor',800,100,'4.7 kOhm');
 wire('power','VCC','oled','VCC');wire('oled','GND','ground','GND');
 wire('mcu','PB6','oled','SCL');wire('mcu','PB7','oled','SDA');
 wire('power','VCC','r-scl','1');wire('r-scl','2','oled','SCL');
 wire('power','VCC','r-sda','1');wire('r-sda','2','oled','SDA');
}else{
 add('matrix','max7219',730,230,'MAX7219',{peripheralProperties:{intensity:3}});
 add('matrix-5v','vcc',670,80,'+5V');add('matrix-gnd','ground',670,450,'0V');
 wire('matrix-5v','VCC','matrix','VCC');wire('matrix','GND','matrix-gnd','GND');
 wire('mcu','PA5','matrix','CLK');wire('mcu','PA7','matrix','DIN');wire('mcu','PB0','matrix','CS');
}

const rectangles=components.map(c=>({id:c.id,x:c.x-8,y:c.y-8,r:c.x+defs[c.type].width+8,b:c.y+defs[c.type].height+8}));
function anchor(id,pin){
 const c=components.find(c=>c.id===id),q=defs[c.type].pins.find(q=>q.name===pin);
 return {...p(id,pin),side:q.side||(q.x===0?'left':q.y===0?'top':q.y===defs[c.type].height?'bottom':'right')};
}
function stub(q){return{x:q.x+(q.side==='left'?-20:q.side==='right'?20:0),y:q.y+(q.side==='top'?-20:q.side==='bottom'?20:0)};}
function crosses(a,b,r){return a.x===b.x?a.x>r.x&&a.x<r.r&&Math.max(a.y,b.y)>r.y&&Math.min(a.y,b.y)<r.b:a.y>r.y&&a.y<r.b&&Math.max(a.x,b.x)>r.x&&Math.min(a.x,b.x)<r.r;}
const xs=new Set([20,1120]),ys=new Set([20,650]),tracks=[];
rectangles.forEach(r=>{xs.add(r.x-8);xs.add(r.r+8);ys.add(r.y-8);ys.add(r.b+8);});
for(const w of wires)for(const e of [w.from,w.to]){const q=stub(anchor(e.componentId,e.pin));xs.add(q.x);ys.add(q.y);}
const xgrid=[...xs].sort((a,b)=>a-b),ygrid=[...ys].sort((a,b)=>a-b);
function routeWire(w){
 const a=anchor(w.from.componentId,w.from.pin),b=anchor(w.to.componentId,w.to.pin),start=stub(a),end=stub(b);
 const si=xgrid.indexOf(start.x),sj=ygrid.indexOf(start.y),ei=xgrid.indexOf(end.x),ej=ygrid.indexOf(end.y),key=(i,j)=>i+','+j;
 const best=new Map([[key(si,sj),0]]),previous=new Map(),open=[{i:si,j:sj,cost:0,score:0,dir:''}];
 while(open.length){
  open.sort((a,b)=>b.score-a.score);const n=open.pop(),k=key(n.i,n.j);if(best.get(k)<n.cost)continue;
  if(n.i===ei&&n.j===ej){
   const points=[end];let cursor=k;
   while(previous.has(cursor)){cursor=previous.get(cursor);const[i,j]=cursor.split(',').map(Number);points.unshift({x:xgrid[i],y:ygrid[j]});}
   const result=[];for(const q of [a,...points,b]){
    const last=result.at(-1),old=result.at(-2);if(last&&last.x===q.x&&last.y===q.y)continue;
    if(old&&last&&((old.x===last.x&&last.x===q.x)||(old.y===last.y&&last.y===q.y)))result.pop();
    result.push({x:q.x,y:q.y});
   }
   w.route=result;for(let i=1;i<result.length;i++)tracks.push({a:result[i-1],b:result[i]});return;
  }
  for(const[di,dj]of[[1,0],[-1,0],[0,1],[0,-1]]){
   const i=n.i+di,j=n.j+dj;if(i<0||j<0||i>=xgrid.length||j>=ygrid.length)continue;
   const p={x:xgrid[n.i],y:ygrid[n.j]},q={x:xgrid[i],y:ygrid[j]};if(rectangles.some(r=>crosses(p,q,r)))continue;
   let penalty=0;for(const t of tracks){const h=p.y===q.y,th=t.a.y===t.b.y;
    if(h===th&&((h&&p.y===t.a.y)||(!h&&p.x===t.a.x))){const d=h?'x':'y';if(Math.min(Math.max(p[d],q[d]),Math.max(t.a[d],t.b[d]))>Math.max(Math.min(p[d],q[d]),Math.min(t.a[d],t.b[d])))penalty+=1000;}
    else if(h!==th){const x=h?t.a.x:p.x,y=h?p.y:t.a.y;if(x>=Math.min(p.x,q.x)&&x<=Math.max(p.x,q.x)&&y>=Math.min(p.y,q.y)&&y<=Math.max(p.y,q.y)&&x>=Math.min(t.a.x,t.b.x)&&x<=Math.max(t.a.x,t.b.x)&&y>=Math.min(t.a.y,t.b.y)&&y<=Math.max(t.a.y,t.b.y))penalty+=80;}
   }
   const dir=di?'h':'v',cost=n.cost+Math.abs(p.x-q.x)+Math.abs(p.y-q.y)+penalty+(n.dir&&n.dir!==dir?18:0),next=key(i,j);
   if(best.has(next)&&best.get(next)<=cost)continue;best.set(next,cost);previous.set(next,k);open.push({i,j,cost,dir,score:cost+Math.abs(q.x-end.x)+Math.abs(q.y-end.y)});
  }
 }
 throw Error('Unable to route '+JSON.stringify(w));
}
wires.forEach(routeWire);
const doc={schemaVersion:1,kind:'AliceSIMCircuit',mcu:'STM32F103C8T6',components,wires,view:{zoom:0.95,panX:0,panY:0,userView:false}};
const result=api.importCircuit(doc);if(!result.ok||result.skippedWireCount)throw Error(JSON.stringify(result));
fs.writeFileSync(path.join(__dirname,name+'.alice-sch.json'),JSON.stringify(doc,null,2)+'\n');
console.log(JSON.stringify({example:name,components:components.length,wires:wires.length}));
