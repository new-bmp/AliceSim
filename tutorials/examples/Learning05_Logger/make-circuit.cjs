function stub(p){const q={x:p.x,y:p.y};q[{left:'x',right:'x',top:'y',bottom:'y'}[p.side]]+=['left','top'].includes(p.side)?-20:20;return q;}
function intersects(a,b,r){
  if(a.x===b.x) return a.x>r.x&&a.x<r.r&&Math.max(a.y,b.y)>r.y&&Math.min(a.y,b.y)<r.b;
  return a.y>r.y&&a.y<r.b&&Math.max(a.x,b.x)>r.x&&Math.min(a.x,b.x)<r.r;
}
