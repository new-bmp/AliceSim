function pushHeap(heap,n){let i=heap.length;heap.push(n);while(i>0){const p=(i-1)>>1;if(heap[p].estimate<=n.estimate)break;heap[i]=heap[p];i=p;}heap[i]=n;}
function popHeap(heap){const top=heap[0],last=heap.pop();if(heap.length){let i=0;while(i*2+1<heap.length){let c=i*2+1;if(c+1<heap.length&&heap[c+1].estimate<heap[c].estimate)c++;if(heap[c].estimate>=last.estimate)break;heap[i]=heap[c];i=c;}heap[i]=last;}return top;}
function route(a,b,signal){
  const start=stub(a),end=stub(b),key=(i,j)=>i+','+j;
  const si=xs.indexOf(start.x),sj=ys.indexOf(start.y),ei=xs.indexOf(end.x),ej=ys.indexOf(end.y);
  const frontier=[{i:si,j:sj,cost:0,dir:'',estimate:Math.abs(start.x-end.x)+Math.abs(start.y-end.y)}],best=new Map(),prev=new Map();
  best.set(key(si,sj),0);
  const endKey=key(ei,ej);
  while(frontier.length){
    const n=popHeap(frontier),k=key(n.i,n.j);
    if(best.has(k)&&best.get(k)<n.cost)continue;
    if(k===endKey){
      const result=[end];let cursor=k;
      while(prev.has(cursor)){cursor=prev.get(cursor);const [i,j]=cursor.split(',').map(Number);result.unshift({x:xs[i],y:ys[j]});}
      const points=[{x:a.x,y:a.y},...result,{x:b.x,y:b.y}];
      const simplified=[];
      for(const p of points){
        const last=simplified.at(-1);if(last&&last.x===p.x&&last.y===p.y)continue;
        const old=simplified.at(-2);
        if(old&&last&&((old.x===last.x&&last.x===p.x)||(old.y===last.y&&last.y===p.y)))simplified.pop();
        simplified.push(p);
      }
      for(let i=1;i<simplified.length;i++)tracks.push({a:simplified[i-1],b:simplified[i],signal});
      return simplified;
    }
    for(const [di,dj] of [[1,0],[-1,0],[0,1],[0,-1]]){
      const i=n.i+di,j=n.j+dj;if(i<0||j<0||i>=xs.length||j>=ys.length)continue;
      const p={x:xs[n.i],y:ys[n.j]},q={x:xs[i],y:ys[j]};
      if(rects.some(r=>intersects(p,q,r)))continue;
      let penalty=0;
      for(const t of tracks){
        const same=signal===t.signal;
        const h=p.y===q.y,th=t.a.y===t.b.y;
        if(h!==th){const x=h?t.a.x:p.x,y=h?p.y:t.a.y;
          if(x>=Math.min(p.x,q.x)&&x<=Math.max(p.x,q.x)&&y>=Math.min(p.y,q.y)&&y<=Math.max(p.y,q.y)&&x>=Math.min(t.a.x,t.b.x)&&x<=Math.max(t.a.x,t.b.x)&&y>=Math.min(t.a.y,t.b.y)&&y<=Math.max(t.a.y,t.b.y))penalty+=same?0:180;
        }else if((h&&p.y===t.a.y)||(!h&&p.x===t.a.x)){
          const l=h?'x':'y';if(Math.min(Math.max(p[l],q[l]),Math.max(t.a[l],t.b[l]))>Math.max(Math.min(p[l],q[l]),Math.min(t.a[l],t.b[l])))penalty+=same?0:1000;
        }
      }
      const dir=di?'h':'v',cost=n.cost+Math.abs(p.x-q.x)+Math.abs(p.y-q.y)+penalty+(n.dir&&n.dir!==dir?18:0),nk=key(i,j);
      if(best.has(nk)&&best.get(nk)<=cost)continue;
      best.set(nk,cost);prev.set(nk,k);pushHeap(frontier,{i,j,cost,dir,estimate:cost+Math.abs(q.x-end.x)+Math.abs(q.y-end.y)});
    }
  }
  throw new Error('No clean wire route: '+signal+' '+JSON.stringify({a,b}));
}
