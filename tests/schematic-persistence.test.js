test("serializeCircuit accepts an exported payload and invalid imports are atomic", () => {
  const api = loadSchematicApi();
  assert.equal(api.importCircuit(JSON.stringify(sampleCircuit())).ok, true);
  const before = api.serializeCircuit();
  const payload = api.exportCircuit();
  const serializedPayload = api.serializeCircuit(payload, 0);
  assert.deepEqual(JSON.parse(serializedPayload), JSON.parse(before));

  const invalid = JSON.parse(before);
  invalid.wires[0].to.pin = "NOT_A_PIN";
  const failed = api.importCircuit(invalid);
  assert.equal(failed.ok, false);
  assert.equal(failed.code, "INVALID_COMPONENT_PIN");
  assert.equal(api.serializeCircuit(), before);
});

test("wire bend editing inserts, removes and persists orthogonal control points", () => {
  const api = loadSchematicApi();
  assert.equal(api.importCircuit(sampleCircuit()).ok, true);
  const before = api.getState().wires[0];
  const inserted = api.insertWireBend(before.id, 2, { x: 295, y: 126 });
  assert.ok(inserted);
  assert.ok(inserted.length > before.route.length);
  for (let index = 1; index < inserted.length; index += 1) {
    assert.ok(inserted[index - 1].x === inserted[index].x || inserted[index - 1].y === inserted[index].y);
  }

  const saved = api.exportCircuit();
  assert.deepEqual(saved.wires[0].route, inserted);
  const bendIndex = inserted.findIndex((point, index) => index > 0 && index < inserted.length - 1 &&
    inserted[index - 1].x !== inserted[index + 1].x && inserted[index - 1].y !== inserted[index + 1].y);
  assert.ok(bendIndex > 0);
  const removed = api.removeWireBend(before.id, bendIndex);
  assert.ok(removed);
  for (let index = 1; index < removed.length; index += 1) {
    assert.ok(removed[index - 1].x === removed[index].x || removed[index - 1].y === removed[index].y);
  }
});

