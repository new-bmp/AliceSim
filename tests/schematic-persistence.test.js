test("DC-DC converter reports efficiency, upstream input power and output overload", () => {
  const api = loadSchematicApi();
  const result = api.importCircuit({
    schemaVersion: 1,
    kind: "AliceSIMCircuit",
    mcu: "STM32F103C8T6",
    components: [
      { id: "supply", type: "vcc", ref: "PWR1", value: "+12 V · 1 A", x: 80, y: 40, rotation: 0 },
      { id: "ground", type: "ground", ref: "GND1", value: "0V", x: 80, y: 300, rotation: 0 },
      { id: "converter", type: "dcDcConverter", ref: "PSU1", value: "5.0 V · 0.25 A · 90%", x: 280, y: 100, rotation: 0, peripheralProperties: { outputVoltageV: 5, maxOutputCurrentA: 0.25, efficiencyPercent: 90, quiescentCurrentMa: 5, enabled: 1 } },
      { id: "load", type: "resistor", ref: "R1", value: "10 Ω · 5 W", x: 520, y: 140, rotation: 0 }
    ],
    wires: [
      { id: "w1", from: { componentId: "supply", pin: "VCC" }, to: { componentId: "converter", pin: "VIN" }, route: [{ x: 112, y: 98 }, { x: 280, y: 98 }, { x: 280, y: 116 }] },
      { id: "w2", from: { componentId: "converter", pin: "GND" }, to: { componentId: "ground", pin: "GND" }, route: [{ x: 280, y: 144 }, { x: 280, y: 300 }, { x: 112, y: 300 }] },
      { id: "w3", from: { componentId: "converter", pin: "VOUT" }, to: { componentId: "load", pin: "1" }, route: [{ x: 396, y: 144 }, { x: 520, y: 144 }, { x: 520, y: 166 }] },
      { id: "w4", from: { componentId: "load", pin: "2" }, to: { componentId: "ground", pin: "GND" }, route: [{ x: 616, y: 166 }, { x: 616, y: 300 }, { x: 112, y: 300 }] }
    ],
    view: { zoom: 1, panX: 0, panY: 0 }
  });
  assert.equal(result.ok, true, JSON.stringify(result));
  const report = api.getPowerReport();
  const converter = report.components.find((entry) => entry.componentId === "converter");
  const supply = report.components.find((entry) => entry.componentId === "supply");
  assert.ok(Math.abs(converter.outputVoltageV - 5) < 1e-9);
  assert.ok(Math.abs(converter.outputCurrentA - 0.5) < 1e-9);
  assert.ok(Math.abs(converter.outputPowerW - 2.5) < 1e-9);
  assert.ok(Math.abs(converter.inputPowerW - (2.5 / 0.9 + 12 * 0.005)) < 1e-9);
  assert.ok(Math.abs(supply.currentA - converter.inputCurrentA) < 1e-9);
  assert.equal(converter.overload, true);
  assert.ok(report.alerts.some((entry) => entry.ref === "PSU1"));

  const saved = api.exportCircuit();
  assert.deepEqual(JSON.parse(JSON.stringify(saved.components.find((entry) => entry.id === "converter").peripheralProperties)), {
    outputVoltageV: 5,
    maxOutputCurrentA: 0.25,
    efficiencyPercent: 90,
    quiescentCurrentMa: 5,
    enabled: 1
  });
});
