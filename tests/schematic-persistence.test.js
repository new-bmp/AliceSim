function loadSchematicApi(options = {}) {
  const window = {
    addEventListener() {},
    AliceOledDevice: require("../oled-device.js"),
    AliceSpiDisplayDevice: require("../spi-display-device.js"),
    AliceLightSensorDevice: require("../light-sensor-device.js"),
    AlicePeripheralCatalog: require("../peripheral-catalog.js"),
    AlicePeripheralDevices: require("../peripheral-devices.js"),
    AliceHalSimulator: options.halSimulator || null
  };
  const document = {
    readyState: "loading",
    addEventListener() {},
    body: null
  };
  const context = vm.createContext({
    window,
    document,
    Blob,
    CustomEvent: function CustomEvent(type, options) {
      this.type = type;
      this.detail = options && options.detail;
    },
    console,
    queueMicrotask,
    setTimeout,
    clearTimeout
  });
  const source = fs.readFileSync(path.join(__dirname, "..", "schematic.js"), "utf8");
  vm.runInContext(source, context, { filename: "schematic.js" });
  return window.AliceSchematic;
}

